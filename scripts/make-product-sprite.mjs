#!/usr/bin/env node
/**
 * Builds public/product-icons.svg: one <symbol> per product picture named in
 * lib/product-icons.ts (PRODUCT_ICON_KEYS), drawn from lucide (ISC licence).
 *
 * Why a sprite and not components: a shop's till can show any of ~80 product
 * pictures, and 80 icon components would add 15-20KB of JavaScript to the
 * sales screen. One SVG file costs no JavaScript at all and is cached by the
 * service worker after the first load.
 *
 * Run after changing the list: `npm run icons:products`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const iconsDir = join(root, 'node_modules', 'lucide-react', 'dist', 'esm', 'icons');
const source = readFileSync(join(root, 'lib', 'product-icons.ts'), 'utf8');
const list = /PRODUCT_ICON_KEYS = \[([\s\S]*?)\] as const/.exec(source);
if (!list) {
  console.error('product sprite — could not find PRODUCT_ICON_KEYS in lib/product-icons.ts');
  process.exit(1);
}
const keys = [...list[1].matchAll(/'([a-z0-9-]+)'/g)].map((m) => m[1]);

const escape = (value) => String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

const symbols = keys.map((key) => {
  let code;
  try {
    code = readFileSync(join(iconsDir, `${key}.mjs`), 'utf8');
  } catch {
    console.error(`product sprite — no lucide icon called ${key}`);
    process.exit(1);
  }
  for (let hops = 0; hops < 3; hops++) {
    const alias = /export \{ default \} from '\.\/([\w-]+\.mjs)'/.exec(code);
    if (!alias) break;
    code = readFileSync(join(iconsDir, alias[1]), 'utf8');
  }
  const match = /const __iconData = (\{[\s\S]*?\n\});/.exec(code);
  if (!match) {
    console.error(`product sprite — could not read ${key}`);
    process.exit(1);
  }
  const node = Function(`return ${match[1]}`)().node;
  const children = node
    .map(([tag, attrs]) => {
      const rest = Object.entries(attrs)
        .filter(([name]) => name !== 'key')
        .map(([name, value]) => `${name}="${escape(value)}"`)
        .join(' ');
      return `<${tag} ${rest}/>`;
    })
    .join('');
  return `<symbol id="${key}" viewBox="0 0 24 24">${children}</symbol>`;
});

const svg =
  '<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' +
  '<!-- Generated by scripts/make-product-sprite.mjs from lucide (ISC). Do not edit by hand. -->' +
  symbols.join('') +
  '</svg>\n';

writeFileSync(join(root, 'public', 'product-icons.svg'), svg);
console.log(`product sprite — ${keys.length} icons, ${(svg.length / 1024).toFixed(1)} KB`);
